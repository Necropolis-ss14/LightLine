using Content.Client.Audio;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio;
using Robust.Shared.IoC;
using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI;

/// <summary>
/// Manual lobby music switcher (previous / current track / next).
/// Replaces the servers hub in the lobby.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyMusicSwitcher : BoxContainer
{
    [Dependency] private IResourceCache _resCache = default!;

    private ContentAudioSystem? _audio;

    public LobbyMusicSwitcher()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _audio = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<ContentAudioSystem>();
        _audio.LobbySoundtrackChanged += UpdateTrack;

        PrevButton.OnPressed += _ => _audio?.PlayPreviousLobbyTrack();
        NextButton.OnPressed += _ => _audio?.PlayNextLobbyTrack();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        if (_audio != null)
            _audio.LobbySoundtrackChanged -= UpdateTrack;
    }

    private void UpdateTrack(LobbySoundtrackChangedEvent ev)
    {
        if (ev.SoundtrackFilename == null
            || !_resCache.TryGetResource<AudioResource>(ev.SoundtrackFilename, out var resource))
        {
            TrackLabel.Text = "—";
            return;
        }

        var stream = resource.AudioStream;
        var title = string.IsNullOrEmpty(stream.Title) ? "?" : stream.Title;
        var artist = string.IsNullOrEmpty(stream.Artist) ? "?" : stream.Artist;
        TrackLabel.Text = $"{title} — {artist}";
    }
}
